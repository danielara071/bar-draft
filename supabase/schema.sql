  SELECT friend_id FROM friendships WHERE user_id = p_user_id AND status = 'accepted'
  UNION
  SELECT user_id FROM friendships WHERE friend_id = p_user_id AND status = 'accepted';
$$;

-- Busca usuarios por nombre (para agregar amigos)
CREATE OR REPLACE FUNCTION public.buscar_amigos(texto_busqueda text)
RETURNS TABLE(id uuid, nombre_usuario text, url_avatar text, logro text)
LANGUAGE sql AS $$
  SELECT u.id, u.nombre, u.url_avatar, l.url_image
  FROM public.profiles AS u
  LEFT JOIN public.logros AS l ON u.logro = l.id
  WHERE u.nombre ILIKE texto_busqueda || '%'
  ORDER BY u.nombre
  LIMIT 10;
$$;

-- Devuelve amigos de un usuario con filtro de estado
CREATE OR REPLACE FUNCTION public.get_friends(p_user_id uuid, f_status text)
RETURNS TABLE(id uuid, nombre_usuario text, url_avatar text, logro text, status text)
LANGUAGE sql AS $$
  SELECT u.id, u.nombre, u.url_avatar, l.url_image, f.status
  FROM public.friendships AS f
  JOIN public.profiles AS u ON u.id = f.friend_id
  LEFT JOIN public.logros AS l ON u.logro = l.id
  WHERE f.user_id = p_user_id AND f.status = f_status;
$$;

-- Devuelve el estado de la relacion entre dos usuarios
CREATE OR REPLACE FUNCTION public.get_friend_status(sender_uuid uuid, receiver_uuid uuid)
RETURNS text LANGUAGE plpgsql AS $$
DECLARE
  request_status text;
BEGIN
  SELECT f.status INTO request_status
  FROM public.friendships f
  WHERE (f.user_id = sender_uuid AND f.friend_id = receiver_uuid)
     OR (f.user_id = receiver_uuid AND f.friend_id = sender_uuid)
  LIMIT 1;
  RETURN COALESCE(request_status, 'none');
END;
$$;

-- Envia solicitud de amistad
CREATE OR REPLACE FUNCTION public.send_request(sender_uuid uuid, receiver_uuid uuid)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM public.friendships
  WHERE (user_id = sender_uuid AND friend_id = receiver_uuid)
     OR (user_id = receiver_uuid AND friend_id = sender_uuid);

  INSERT INTO public.friendships (user_id, friend_id, status)
  VALUES (sender_uuid, receiver_uuid, 'pending');

  INSERT INTO public.friendships (user_id, friend_id, status)
  VALUES (receiver_uuid, sender_uuid, 'request');
END;
$$;

-- Acepta solicitud de amistad
CREATE OR REPLACE FUNCTION public.accept_request(sender_uuid uuid, receiver_uuid uuid)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  UPDATE public.friendships
  SET status = 'accepted'
  WHERE (user_id = sender_uuid AND friend_id = receiver_uuid)
     OR (user_id = receiver_uuid AND friend_id = sender_uuid);
END;
$$;

-- Elimina relacion de amistad
CREATE OR REPLACE FUNCTION public.delete_friendship(sender_uuid uuid, receiver_uuid uuid)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM public.friendships
  WHERE (user_id = sender_uuid AND friend_id = receiver_uuid)
     OR (user_id = receiver_uuid AND friend_id = sender_uuid);
END;
$$;

-- Lista trofeos con coordenadas geograficas
CREATE OR REPLACE FUNCTION public.obtener_lista_trofeos()
RETURNS TABLE(id uuid, nombre text, descripcion text, coordenadas float8[])
LANGUAGE plpgsql AS $$
BEGIN
  RETURN QUERY
  SELECT t.id, t.nombre::TEXT, t.descripcion::TEXT,
         ARRAY[u.latitud, u.longitud]::FLOAT8[] AS coordenadas
  FROM trofeos t
  INNER JOIN ubicacion_trofeo u ON t.id = u.trofeo_id;
END;
$$;

-- Trigger function: crea perfil automaticamente al registrarse
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
  INSERT INTO public.profiles (id, email, nombre, url_avatar)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.raw_user_meta_data->>'name', 'Nuevo Socio'),
    COALESCE(NEW.raw_user_meta_data->>'avatar_url', NEW.raw_user_meta_data->>'picture', '')
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'Error en handle_new_user para el usuario %: %', NEW.id, SQLERRM;
  RETURN NEW;
END;
$$;

-- Trigger function: recalcula nivel al actualizar puntos
CREATE OR REPLACE FUNCTION public.actualizar_nivel()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.puntos > 8000 THEN NEW.puntos := 8000; END IF;
  IF NEW.puntos < 0 THEN NEW.puntos := 0; END IF;
  NEW.nivel := calcular_nivel(NEW.puntos);
  RETURN NEW;
END;
$$;


-- ============================================================
-- TRIGGERS
-- ============================================================

-- Crea perfil automaticamente cuando se registra un usuario
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Recalcula nivel cuando cambian los puntos del perfil
CREATE TRIGGER trigger_actualizar_nivel
  BEFORE INSERT OR UPDATE ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.actualizar_nivel();


