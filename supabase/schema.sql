-- Devuelve los logros de un usuario indicando cuales ha desbloqueado
CREATE OR REPLACE FUNCTION public.get_user_logros(p_id uuid)
RETURNS TABLE(id bigint, nombre text, descripcion text, url_image text, desbloqueado boolean)
LANGUAGE plpgsql AS $$
BEGIN
  RETURN QUERY
  SELECT
    l.id, l.nombre, l.descripcion, l.url_image,
    CASE WHEN lu.usuario_id IS NOT NULL THEN true ELSE false END AS desbloqueado
  FROM public.logros AS l
  LEFT JOIN public.logros_obtenidos_usuarios AS lu
    ON lu.logro_id = l.id AND lu.usuario_id = p_id
  ORDER BY l.id;
END;
$$;

