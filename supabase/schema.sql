-- Genera un codigo unico de sala para Watch Party (formato XKP-7823)
CREATE OR REPLACE FUNCTION public.generate_unique_room_code()
RETURNS text LANGUAGE plpgsql AS $$
DECLARE
  new_code text;
  exists   boolean;
BEGIN
  LOOP
    new_code := upper(substring(md5(random()::text) FROM 1 FOR 3))
             || '-'
             || lpad(floor(random() * 9000 + 1000)::text, 4, '0');
    SELECT EXISTS (
      SELECT 1 FROM watch_parties WHERE code = new_code
    ) INTO exists;
    EXIT WHEN NOT exists;
  END LOOP;
  RETURN new_code;
END;
$$;

-- Valida un codigo de sala y devuelve la Watch Party
CREATE OR REPLACE FUNCTION public.validate_room_code(p_code text)
RETURNS TABLE(id uuid, code text, name text, fixture_id text, home_team text, away_team text, match_date timestamptz, privacy text, created_by uuid)
LANGUAGE sql AS $$
  SELECT id, code, name, fixture_id, home_team, away_team, match_date, privacy, created_by
  FROM watch_parties
  WHERE code = p_code
  LIMIT 1;
$$;

-- Devuelve los IDs de amigos aceptados de un usuario
