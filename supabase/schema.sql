-- Calcula el nivel en base a puntos XP
CREATE OR REPLACE FUNCTION public.calcular_nivel(xp bigint)
RETURNS smallint LANGUAGE plpgsql AS $$
BEGIN
  IF xp >= 8000 THEN RETURN 5;
  ELSIF xp >= 6000 THEN RETURN 4;
  ELSIF xp >= 4000 THEN RETURN 3;
  ELSIF xp >= 2000 THEN RETURN 2;
  ELSE RETURN 1;
  END IF;
END;
$$;

-- Suma monedas al perfil de un usuario (evita race conditions)
CREATE OR REPLACE FUNCTION public.add_monedas(p_user_id uuid, p_amount integer)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
  UPDATE public.profiles
  SET monedas = monedas + p_amount
  WHERE id = p_user_id;
END;
$$;

-- Agrega una palabra al banco del Wordle
CREATE OR REPLACE FUNCTION public.add_word(new_word text, scheduled_date date DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO public.wordle_words (word, used_on)
  VALUES (LOWER(new_word), scheduled_date);
END;
$$;

-- Elimina una palabra del banco del Wordle
CREATE OR REPLACE FUNCTION public.delete_word(p_word text)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM wordle_words WHERE word = p_word;
END;
$$;

